/**
 * Returns metadata for a given pathname with clean normalized fallback.
 */
export function getRouteMeta(pathname) {
  if (!pathname) return DEFAULT_META;

  // Normalize path (remove trailing slash except for root)
  const cleanPath = pathname.length > 1 && pathname.endsWith('/') 
    ? pathname.slice(0, -1) 
    : pathname;

  // Exact match
  if (ROUTES_META[cleanPath]) {
    return ROUTES_META[cleanPath];
  }

  // Blog single post fallback
  if (cleanPath.startsWith('/blog/')) {
    return {
      title: "Blog Article | Samba Soccer Schools",
      description: "Read our latest article and parenting football advice from Samba Soccer Schools.",
      keywords: "samba soccer blog, youth football advice"
    };
  }

  // Fallback 404
  return {
    title: "Page Not Found | Samba Soccer Schools",
    description: "The page you are looking for does not exist. Return to Samba Soccer Schools homepage.",
    keywords: "samba soccer schools, 404"
  };
}
